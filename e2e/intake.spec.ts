import { test,expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { emptyIntake } from '../src/lib/intake';
const principal=(id:string,role:string)=>Buffer.from(JSON.stringify({auth_typ:'aad',name_typ:'name',role_typ:'roles',claims:[{typ:'oid',val:id},{typ:'name',val:id},{typ:'roles',val:role}]})).toString('base64');
test('agent saves and resumes a fictional draft, submits it, and sees stored lead metrics',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setExtraHTTPHeaders({'x-ms-client-principal':principal('fictional-browser-agent','agent')});
  await page.goto('/intake');
  await page.getByLabel('First name',{exact:true}).fill('Fictional Browser');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'Applicant consent is required'})).toContainText('Applicant consent is required');
  await page.getByRole('checkbox').check();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/intakes'));
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  const savedResponse=await responsePromise;
  expect(savedResponse.status(),JSON.stringify(await savedResponse.json())).toBe(201);
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.getByRole('link',{name:'Back to leads'}).click();
  await expect(page.getByRole('table')).toContainText('Fictional Browser');
  await page.getByRole('link',{name:'Resume draft'}).click();
  await expect(page.getByLabel('First name',{exact:true})).toHaveValue('Fictional Browser');
  await page.getByLabel('Last name',{exact:true}).fill('Applicant');
  await page.getByLabel('Date of birth').fill('1990-01-01');
  await page.getByLabel('Mobile phone').fill('2025550199');
  await page.getByLabel('Email address').fill('fictional@example.test');
  await page.getByLabel('Home address').fill('123 Fictional Lane');
  await page.getByLabel('County',{exact:true}).fill('Test County');
  await page.getByLabel('ZIP code').fill('20001');
  await page.getByLabel('Household size').fill('2');
  await page.getByLabel('Estimated annual household income').fill('42000');
  await page.getByRole('button',{name:'Save and prepare quote'}).click();
  await expect(page.getByRole('status')).toContainText('ready for quote preparation');
  await expect(page.getByLabel('First name',{exact:true})).toBeDisabled();
  await page.reload();
  await expect(page.getByRole('status')).toContainText('ready for quote preparation');
  await page.goto('/');
  await expect(page.getByRole('region',{name:'Pipeline summary'})).toContainText('All leads1');
  await expect(page.getByRole('table')).toContainText('Fictional Browser Applicant');
  await page.goto('/leads?q=missing');await expect(page.getByText('No leads found.')).toBeVisible();
  expect(errors).toEqual([]);
});
test('browser role restrictions and unauthenticated API requests',async({page,request})=>{
  expect((await request.get('/api/leads')).status()).toBe(401);
  const id=randomUUID();
  expect((await request.post('/api/intakes',{headers:{'x-ms-client-principal':principal('fictional-owner','agent')},data:{id,version:0,intent:'draft',data:{...emptyIntake(),firstName:'Fictional Role Fixture'}}})).status()).toBe(201);
  await page.setExtraHTTPHeaders({'x-ms-client-principal':principal('fictional-other-agent','agent')});
  await page.goto('/leads');await expect(page.getByText('No leads found.')).toBeVisible();
  expect((await page.goto(`/intake?id=${id}`))?.status()).toBe(404);
  await page.setExtraHTTPHeaders({'x-ms-client-principal':principal('fictional-viewer','viewer')});
  await page.goto('/intake');await expect(page.getByText('Only agents and administrators can save intake information.')).toBeVisible();
  const response=await page.request.post('/api/intakes',{data:{},headers:{'x-ms-client-principal':principal('fictional-viewer','viewer')}});expect(response.status()).toBe(403);
  await page.setExtraHTTPHeaders({'x-ms-client-principal':principal('fictional-admin','admin')});
  await page.goto('/leads');await expect(page.getByRole('table')).toContainText('Fictional Role Fixture');
});

test('admin links an existing case, records consent, and sees quote results and the disabled handoff boundary',async({page})=>{
  const identity=principal('fictional-workflow-admin','admin');
  await page.setExtraHTTPHeaders({'x-ms-client-principal':identity});
  const id=randomUUID();
  expect((await page.request.post('/api/intakes',{data:{id,version:0,intent:'submit',data:{...emptyIntake(),firstName:'Fictional Workflow',lastName:'Applicant',dob:'1990-01-01',phone:'2025550100',email:'workflow@example.test',address:'123 Fictional Lane',county:'Test',zipCode:'20001',householdSize:1,income:42000,coverageYear:2027}}})).status()).toBe(201);
  await page.goto(`/intake?id=${id}`);
  const workspace=page.getByRole('region',{name:'HealthSherpa enrollment workspace'});
  await workspace.getByRole('button',{name:'Open or resume enrollment case'}).click();
  await expect(workspace).toContainText('Awaiting administrator reconciliation');
  await workspace.getByLabel('Consent evidence reference').fill('fictional-consent-document');
  await workspace.getByRole('button',{name:'Record granted consent'}).click();
  await expect(workspace).toContainText('Assistance consent: granted');
  await workspace.getByLabel('Hub client ID',{exact:true}).fill(randomUUID());
  await workspace.getByLabel('Hub office ID',{exact:true}).fill(randomUUID());
  await workspace.getByLabel('I verified the household').check();
  await workspace.getByRole('button',{name:'Link reviewed records'}).click();
  await expect(workspace).toContainText('Hub client: Linked');
  // Browser response fixtures only; server contract/ownership/DB boundaries are covered in Vitest.
  await page.route('**/api/healthsherpa/counties?*',route=>route.fulfill({json:{data:[{fips_code:'11001',name:'Fictional County',state:'DC'}]}}));
  await page.route('**/api/healthsherpa/quotes',route=>route.fulfill({json:{data:{plans:[{plan_id:'fictional-plan',name:'Fictional Silver',pricing:{net_premium:123.45}}],meta:{result_count:1}}}}));
  await workspace.getByRole('button',{name:'Look up counties for saved ZIP'}).click();
  await workspace.getByLabel('County',{exact:true}).selectOption('11001');
  await workspace.getByLabel('Requested effective date').fill('2027-01-01');
  await workspace.getByLabel('Applicant 1 age').fill('36');
  await workspace.getByLabel('Tobacco use').selectOption('false');
  await workspace.getByRole('button',{name:'Request quotes'}).click();
  await expect(workspace.getByRole('table')).toContainText('Fictional Silver');
  await expect(workspace.getByRole('table')).toContainText('$123.45');
  await workspace.getByRole('button',{name:'Create or resume HealthSherpa handoff'}).click();
  await expect(workspace.getByRole('status')).toContainText('approval and OAuth verification required');
  await workspace.getByRole('button',{name:'Record revocation'}).click();
  await expect(workspace).toContainText('Assistance consent: revoked');
  await expect(workspace.getByRole('button',{name:'Request quotes'})).toBeDisabled();
  await expect(workspace.getByRole('table')).toHaveCount(0);
});
